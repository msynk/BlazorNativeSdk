namespace BlazorNativeSdk.Browser;

/// <summary>Options for the browser adapter registered with <c>AddBrowser()</c>.</summary>
public sealed class BrowserNativeOptions
{
    /// <summary>The default path of the adapter's JavaScript module.</summary>
    public const string DefaultModulePath = "./_content/BlazorNativeSdk.Browser/blazor-native-sdk.js";

    /// <summary>
    /// Enables <see cref="Devices.ISecureStorage"/> with <see cref="Devices.SecureStorageProtection.BestEffort"/> protection.
    /// Default: <see langword="false"/>.
    /// </summary>
    /// <remarks>
    /// Browsers cannot protect secrets from scripts running in the page. When enabled, values are encrypted with a
    /// non-extractable AES-GCM 256 key generated by WebCrypto and stored, together with the ciphertext, in IndexedDB. This
    /// protects against casual inspection and copying of the storage files, not against cross-site scripting: any script
    /// running in the origin can ask the browser to decrypt the values.
    /// </remarks>
    public bool EnableBestEffortSecureStorage { get; set; }

    /// <summary>The IndexedDB database used by best-effort secure storage. Default: <c>blazor-native-sdk-secure-storage</c>.</summary>
    public string SecureStorageDatabaseName { get; set; } = "blazor-native-sdk-secure-storage";

    /// <summary>
    /// The query parameter that carries protocol-handler URLs, as produced by
    /// <c>navigator.registerProtocolHandler('web+myapp', '/?bns-link=%s')</c>. Default: <c>bns-link</c>.
    /// </summary>
    public string ProtocolHandlerQueryParameter { get; set; } = "bns-link";

    /// <summary>
    /// Use the File System Access API (<c>showOpenFilePicker</c>/<c>showSaveFilePicker</c>) when the browser provides it.
    /// Default: <see langword="true"/>. When <see langword="false"/> files are opened with a file input and saved as downloads.
    /// </summary>
    public bool UseFileSystemAccessApi { get; set; } = true;

    /// <summary>
    /// Show notifications through the active service worker registration when one exists, which enables action buttons and
    /// taps after the page was closed. Default: <see langword="true"/>.
    /// </summary>
    public bool UseServiceWorkerNotifications { get; set; } = true;

    /// <summary>The path of the adapter's JavaScript module. Change it only when static web assets are served from another base path.</summary>
    public string ModulePath { get; set; } = DefaultModulePath;

    /// <summary>
    /// The timeout for short JavaScript calls (feature probes, clipboard, storage). Operations that show UI (camera, pickers,
    /// share) are not limited by it; they end when the user finishes or the caller's token is cancelled. Default: 30 seconds.
    /// </summary>
    public TimeSpan InteropTimeout { get; set; } = TimeSpan.FromSeconds(30);

    /// <summary>Texts and accessible labels of the built-in camera and scanner overlay. Localize them here.</summary>
    public BrowserOverlayText OverlayText { get; } = new();
}

/// <summary>User-visible texts of the camera and barcode overlay rendered by the browser adapter.</summary>
public sealed class BrowserOverlayText
{
    /// <summary>The dialog title for photo and video capture when the request has no title.</summary>
    public string CameraTitle { get; set; } = "Camera";

    /// <summary>The dialog title for barcode scanning.</summary>
    public string ScannerTitle { get; set; } = "Scan code";

    /// <summary>The hint shown while scanning when the request has no prompt.</summary>
    public string ScannerPrompt { get; set; } = "Point the camera at a barcode or QR code";

    /// <summary>The label of the shutter button.</summary>
    public string Capture { get; set; } = "Take photo";

    /// <summary>The label of the record button.</summary>
    public string StartRecording { get; set; } = "Start recording";

    /// <summary>The label of the record button while recording.</summary>
    public string StopRecording { get; set; } = "Stop recording";

    /// <summary>The label of the cancel button.</summary>
    public string Cancel { get; set; } = "Cancel";

    /// <summary>The label of the switch-camera button.</summary>
    public string SwitchCamera { get; set; } = "Switch camera";
}
